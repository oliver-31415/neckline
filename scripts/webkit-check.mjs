import { webkit } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/webkit-2272/pw_run.sh';
const b = await webkit.launch({ executablePath: exe, headless: true });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
p.on('console', (m) => m.type() === 'error' && errs.push('console: ' + m.text()));
await p.goto(process.argv[2] ?? 'https://oliver-31415.github.io/neckline/');
await p.waitForTimeout(4000);
console.log('body length', (await p.content()).length, 'has app', await p.locator('.app').count());
console.log(errs.join('\n'));
await b.close();
